// XTUsage maps Win32's set-1 scancode and extended bit to physical USB HID.
// Zero means unknown; no layout-dependent virtual-key guess is made.
func XTUsage(scan uint8, extended bool) uint16 {
	if extended {
		switch scan {
		case 0x1c:
			return 0x58
		case 0x1d:
			return 0xe4
		case 0x35:
			return 0x54
		case 0x36:
			return 0xe5
		case 0x37:
			return 0x46
		case 0x38:
			return 0xe6
		case 0x45:
			return 0x53
		case 0x46:
			return 0x48
		case 0x47:
			return 0x4a
		case 0x48:
			return 0x52
		case 0x49:
			return 0x4b
		case 0x4b:
			return 0x50
		case 0x4d:
			return 0x4f
		case 0x4f:
			return 0x4d
		case 0x50:
			return 0x51
		case 0x51:
			return 0x4e
		case 0x52:
			return 0x49
		case 0x53:
			return 0x4c
		case 0x5b:
			return 0xe3
		case 0x5c:
			return 0xe7
		case 0x5d:
			return 0x65
		case 0x5e:
			return 0x66
		}
		return 0
	}
	switch scan {
	case 0x45:
		return 0x48
	case 0x54:
		return 0x46
	case 0x59:
		return 0x67
	case 0x70:
		return 0x88
	case 0x71:
		return 0x91
	case 0x72:
		return 0x90
	case 0x73:
		return 0x87
	case 0x76:
		return 0x73
	case 0x77:
		return 0x93
	case 0x78:
		return 0x92
	case 0x79:
		return 0x8a
	case 0x7b:
		return 0x8b
	case 0x7d:
		return 0x89
	case 0x7e:
		return 0x85
	}
	if scan >= 0x64 && scan <= 0x6e {
		return 0x68 + uint16(scan-0x64)
	}
	if int(scan) < len(xtUsage) {
		return xtUsage[scan]
	}
	return 0
}

// KeyMessage translates a Win32 key message. IME and synthetic Unicode are
// left to the window system; Alt+F4 remains the standard close shortcut.
func KeyMessage(msg uint32, vk, lp uintptr) (Event, bool) {
	if msg != 0x0100 && msg != 0x0101 && msg != 0x0104 && msg != 0x0105 {
		return Event{}, false
	}
	if vk == 0xe5 || vk == 0xe7 || ((msg == 0x0104 || msg == 0x0105) && vk == 0x73 && lp&(1<<29) != 0) {
		return Event{}, false
	}
	usage := XTUsage(uint8((lp>>16)&0xff), lp&(1<<24) != 0)
	if usage == 0 {
		return Event{}, false
	}
	kind := "key_down"
	if msg == 0x0101 || msg == 0x0105 {
		kind = "key_up"
	}
	return Event{Kind: kind, Usage: usage}, true
}
